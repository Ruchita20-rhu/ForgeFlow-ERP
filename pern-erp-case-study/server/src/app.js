import express from 'express';
import cors from 'cors';
import authRoutes from './routes/auth.js';
import catalogRoutes from './routes/catalog.js';
import enquiryRoutes from './routes/enquiries.js';
import quotationRoutes from './routes/quotations.js';
import salesOrderRoutes from './routes/salesOrders.js';
import { authenticate, allowRoles } from './middleware/auth.js';
import { errorHandler } from './utils/errors.js';
export const app=express();
app.use(cors({origin:process.env.CLIENT_ORIGIN||'http://localhost:5173'}));
app.use(express.json({limit:'1mb'}));
app.get('/api/health',(req,res)=>res.json({status:'ok'}));
app.use('/api/auth',authRoutes);
app.use('/api',authenticate);
app.use('/api',catalogRoutes);
app.use('/api/enquiries',allowRoles('ADMIN','SALES'),enquiryRoutes);
app.use('/api/quotations',allowRoles('ADMIN','SALES'),quotationRoutes);
app.use('/api/sales-orders',allowRoles('ADMIN','SALES'),salesOrderRoutes);
app.use((req,res)=>res.status(404).json({error:'Route not found'}));
app.use(errorHandler);
